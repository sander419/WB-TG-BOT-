#!/bin/sh
# Точка входа контейнера: применить миграции, затем запустить сервер.
#
# set -e обязателен: без него неудачная миграция не остановит запуск, и сервис
# поднимется на схеме, которой не соответствует код. Ожидание базы и разбор
# ошибок соединения — внутри мигратора (server/scripts/migrate.ts).
set -e

node dist/migrate.cjs

echo "Запускаю сервер…"
exec node dist/server.cjs
